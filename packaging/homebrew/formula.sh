#!/bin/sh
# Print the Homebrew formula for a release.
#   packaging/homebrew/formula.sh <version> <SHA256SUMS.txt> <download base URL>  > agent-countercheck.rb
# The result goes in the tap repo datacrate360/homebrew-tap as Formula/agent-countercheck.rb, so users run
# (the tap's formula_renames.json sends the old name, countercheck, here):
#   brew install datacrate360/tap/agent-countercheck
set -eu
version="$1"; sums="$2"; base="$3"

sum() {
  s="$(awk -v f="countercheck-$version-$1.tar.gz" '$2 == f || $2 == "*"f {print $1}' "$sums")"
  [ -n "$s" ] || { echo "formula.sh: no checksum for $1 in $sums" >&2; exit 1; }
  printf '%s' "$s"
}

mac="$(sum macos-universal)"
lx="$(sum linux-x86_64)"
la="$(sum linux-aarch64)"

cat <<EOF
# Generated by packaging/homebrew/formula.sh in datacrate360/agent-countercheck; do not edit by hand.
class AgentCountercheck < Formula
  desc "Proof that AI agents' work really happened: re-runs checks and writes a receipt"
  homepage "https://countercheck.datacrate360.ai"
  version "$version"
  license "MIT"

  on_macos do
    url "$base/countercheck-$version-macos-universal.tar.gz"
    sha256 "$mac"
  end

  on_linux do
    on_intel do
      url "$base/countercheck-$version-linux-x86_64.tar.gz"
      sha256 "$lx"
    end
    on_arm do
      url "$base/countercheck-$version-linux-aarch64.tar.gz"
      sha256 "$la"
    end
  end

  def install
    bin.install "countercheck"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/countercheck --version")
  end
end
EOF
